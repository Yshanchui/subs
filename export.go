func aggregate(s State, c Collection) ([]Proxy, map[string]time.Time) {
	chosen := map[string]bool{}
	for _, id := range c.SourceIDs {
		chosen[id] = true
	}
	var out []Proxy
	seen := map[string]bool{}
	names := map[string]bool{"DIRECT": true, "REJECT": true, "GLOBAL": true}
	if s.ACL != nil {
		for _, g := range s.ACL.Groups {
			names[g.Name] = true
		}
	}
	sources := map[string]time.Time{}
	for _, src := range s.Sources {
		if !src.Enabled || (!c.AllSources && !chosen[src.ID]) {
			continue
		}
		if len(src.Cache) == 0 {
			continue
		}
		sources[src.ID] = src.UpdatedAt
		for _, node := range src.Cache {
			p := Proxy{}
			for k, v := range node {
				if k != "name" && k != "__uri" {
					p[k] = v
				}
			}
			b, _ := json.Marshal(p)
			key := string(b)
			if seen[key] {
				continue
			}
			seen[key] = true
			base := cleanName(src.Name + " · " + text(node, "name"))
			name := base
			for n := 2; names[name]; n++ {
				name = base + fmt.Sprintf(" (%d)", n)
			}
			names[name] = true
			p["name"] = name
			p["__original_name"] = text(node, "name")
			if raw := text(node, "__uri"); raw != "" {
				p["__uri"] = raw
			}
			out = append(out, p)
		}
	}
	return out, sources
}

func legacyProxy(p Proxy) (Proxy, bool) {
	t := text(p, "type")
	if !strings.Contains("|ss|ssr|vmess|trojan|snell|socks5|http|", "|"+t+"|") {
		return nil, false
	}
	if p["reality-opts"] != nil {
		return nil, false
	}
	if t == "ss" && (strings.HasPrefix(text(p, "cipher"), "2022-") || text(p, "plugin") == "shadow-tls") {
		return nil, false
	}
	if t == "snell" && integer(p["version"]) > 3 {
		return nil, false
	}
	n := Proxy{}
	for k, v := range p {
		if k != "__uri" && k != "client-fingerprint" && k != "packet-encoding" && k != "smux" && k != "dialer-proxy" && k != "tfo" && k != "ip-version" {
			n[k] = v
		}
	}
	return n, true
}

func makeGroups(groups []Group, nodes []Proxy) []map[string]any {
	var out []map[string]any
	for _, g := range groups {
		var names []string
		seen := map[string]bool{}
		for _, opt := range g.Options {
			if ref, ok := strings.CutPrefix(opt, "[]"); ok {
				if !seen[ref] {
					names = append(names, ref)
					seen[ref] = true
				}
				continue
			}
			re := regexp.MustCompile(opt)
			for _, p := range nodes {
				n := text(p, "name")
				if re.MatchString(first(text(p, "__original_name"), n)) && !seen[n] {
					names = append(names, n)
					seen[n] = true
				}
			}
		}
		t := g.Type
		if len(names) == 0 {
			names = []string{"REJECT"}
			t = "select"
		}
		m := map[string]any{"name": g.Name, "type": t, "proxies": names}
		if t != "select" {
			m["url"] = g.URL
			m["interval"] = g.Interval
			if t == "url-test" {
				m["tolerance"] = g.Tolerance
			}
		}
		out = append(out, m)
	}
	return out
}

func ruleSupported(kind, format string) bool {
	if format == "shadowrocket-rules" {
		return strings.Contains("|DOMAIN|DOMAIN-SUFFIX|DOMAIN-KEYWORD|IP-CIDR|IP-CIDR6|GEOIP|URL-REGEX|USER-AGENT|DST-PORT|SRC-IP-CIDR|MATCH|", "|"+kind+"|")
	}
	if kind == "URL-REGEX" || kind == "USER-AGENT" {
		return false
	}
	if format == "clash" && (kind == "DOMAIN-REGEX" || kind == "IP-ASN" || kind == "PROCESS-PATH") {
		return false
	}
	return true
}

func shadowAction(acl *ACL, policy string) string {
	if policy == "DIRECT" || policy == "REJECT" {
		return policy
	}
	for _, g := range acl.Groups {
		if g.Name == policy && len(g.Options) > 0 {
			if g.Options[0] == "[]DIRECT" {
				return "DIRECT"
			}
			if g.Options[0] == "[]REJECT" {
				return "REJECT"
			}
		}
	}
	return "PROXY"
}

func renderRules(acl *ACL, format string) ([]string, int) {
	var rules []string
	skipped := 0
	for _, r := range acl.Rules {
		if !ruleSupported(r.Kind, format) || (format == "shadowrocket-rules" && strings.Contains(r.Value, ",")) {
			skipped++
			continue
		}
		kind := r.Kind
		policy := r.Policy
		if format == "shadowrocket-rules" {
			policy = shadowAction(acl, policy)
			if kind == "MATCH" {
				kind = "FINAL"
			}
			if kind == "IP-CIDR6" {
				kind = "IP-CIDR6"
			}
		}
		line := kind
		if r.Value != "" {
			line += "," + r.Value
		}
		line += "," + policy
		if r.NoResolve {
			line += ",no-resolve"
		}
		rules = append(rules, line)
	}
	return rules, skipped
}

func renderArtifact(format string, nodes []Proxy, acl *ACL) ([]byte, Artifact, error) {
	a := Artifact{}
	if acl == nil || len(acl.Rules) == 0 {
		return nil, a, errors.New("ACL 规则尚未下载，请先更新规则")
	}
	header := "# Generated by Subs. ACL4SSR: https://github.com/ACL4SSR/ACL4SSR (CC BY-SA 4.0).\n# Local snapshot; downloading this file never fetches upstream subscriptions.\n"
	var b []byte
	if format == "shadowrocket-rules" {
		rules, skip := renderRules(acl, format)
		a.Rules = len(rules)
		a.ExcludedRules = skip
		b = []byte(header + "# Shadowrocket: import nodes subscription in Home; import this file in Config.\n[General]\nbypass-system = true\nskip-proxy = 127.0.0.1, localhost, *.local\n\n[Rule]\n" + strings.Join(rules, "\n") + "\n")
	} else if format == "shadowrocket" {
		var uris []string
		for _, p := range nodes {
			u, e := proxyURI(p)
			if e != nil {
				a.ExcludedNodes++
				continue
			}
			uris = append(uris, u)
		}
		if len(uris) == 0 {
			return nil, a, errors.New("没有可导出为 Shadowrocket 的节点")
		}
		a.Nodes = len(uris)
		b = []byte(base64.StdEncoding.EncodeToString([]byte(strings.Join(uris, "\n"))) + "\n")
	} else {
		var filtered []Proxy
		for _, p := range nodes {
			if format == "clash" {
				n, ok := legacyProxy(p)
				if !ok {
					a.ExcludedNodes++
					continue
				}
				filtered = append(filtered, n)
			} else {
				n := Proxy{}
				for k, v := range p {
					if k != "__uri" {
						n[k] = v
					}
				}
				filtered = append(filtered, n)
			}
		}
		if len(filtered) == 0 {
			return nil, a, errors.New("没有该客户端支持的节点；请使用 Mihomo 格式或添加兼容源")
		}
		rules, skip := renderRules(acl, format)
		a.Nodes = len(filtered)
		a.Rules = len(rules)
		a.ExcludedRules = skip
		outputNodes := make([]Proxy, 0, len(filtered))
		for _, p := range filtered {
			n := Proxy{}
			for k, v := range p {
				if !strings.HasPrefix(k, "__") {
					n[k] = v
				}
			}
			outputNodes = append(outputNodes, n)
		}
		config := map[string]any{"mixed-port": 7890, "allow-lan": false, "mode": "rule", "log-level": "info", "proxies": outputNodes, "proxy-groups": makeGroups(acl.Groups, filtered), "rules": rules}
		if format == "mihomo" {
			config["ipv6"] = false
			config["dns"] = map[string]any{
				"enable":                  true,
				"listen":                  "127.0.0.1:7874",
				"ipv6":                    false,
				"use-hosts":               true,
				"respect-rules":           true,
				"enhanced-mode":           "fake-ip",
				"fake-ip-range":           "198.18.0.1/16",
				"default-nameserver":      []string{"223.5.5.5", "119.29.29.29"},
				"nameserver":              []string{"https://dns.alidns.com/dns-query", "https://doh.pub/dns-query"},
				"proxy-server-nameserver": []string{"https://dns.alidns.com/dns-query", "https://doh.pub/dns-query"},
				"fake-ip-filter": []string{
					"*.lan", "*.localdomain", "*.invalid", "*.localhost", "*.test", "*.local", "*.home.arpa", "localhost",
					"+.msftconnecttest.com", "+.msftncsi.com", "time.*.com", "time.*.gov", "time.*.edu.cn",
					"+.pool.ntp.org", "+.ntp.org.cn", "stun.*.*", "stun.*.*.*",
				},
			}
			config["sniffer"] = map[string]any{
				"enable":               true,
				"force-dns-mapping":    true,
				"parse-pure-ip":        false,
				"override-destination": true,
				"sniff": map[string]any{
					"HTTP": map[string]any{"ports": []int{80, 443, 8080}, "override-destination": true},
					"TLS":  map[string]any{"ports": []int{443, 8443}},
				},
			}
		}
		var err error
		b, err = yaml.Marshal(config)
		if err != nil {
			return nil, a, err
		}
		b = append([]byte(header), b...)
	}
	hash := sha256.Sum256(b)
	a.SHA256 = hex.EncodeToString(hash[:])
	return b, a, nil
}

